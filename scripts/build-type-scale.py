#!/usr/bin/env python3
"""Writes public/css/type-scale.css — the one fluid type scale of the site (React app and static pages both read it).

Each step is  clamp(min, intercept + slope * 100vw, max)  in rem, so:
  - the size grows smoothly from MIN_VW (a phone) to MAX_VW (the desktop design) — no jumps at breakpoints;
  - the desktop value is exactly the design's, the phone value the design's mobile one;
  - every bound is in rem, so the reader's own text-size setting scales the whole ladder (WCAG 1.4.4);
  - no step grows more than 2.5x from its smallest to its largest value — the ceiling below which text with a vw term
    still reaches 200% when the page is zoomed (WCAG 1.4.4 Resize Text, AA);
  - nothing is smaller than 14px (0.875rem).
Run:  python3 scripts/build-type-scale.py
"""
MIN_VW, MAX_VW = 375, 1280          # px: phone design width, desktop design width (Tailwind `xl`)
# name: (size at MIN_VW, size at MAX_VW, line-height at MIN_VW, line-height at MAX_VW, letter-spacing) — px
STEPS = {
    # the static pages' ladder 14/16/18/22/28/36/48 (desktop values); phone values step one rung down, never under 14
    "xs":   (14, 15, 22, 22, "0"),
    "sm":   (15, 16, 24, 26, "0"),
    "md":   (16, 18, 24, 28, "0"),
    "lg":   (20, 22, 28, 28, "-0.03em"),
    "xl":   (24, 28, 30, 34, "-0.02em"),
    "2xl":  (28, 36, 34, 42, "-0.02em"),
    "3xl":  (36, 48, 42, 54, "-0.02em"),
    # the React app's roles (src/styles/globals.css): h1 32/38 -> 72/76, h2 20/28 -> 36/42, h3 15/20 -> 22/28 ...
    # h1 reaches 72 only at 1440: on a 1280 laptop the old site sets ~64, and a 72 there read as gigantic
    "h1":   (32, 72, 38, 76, "-0.02em", 1440),
    "h2":   (20, 36, 28, 42, "-0.02em"),
    "h3":   (15, 22, 20, 28, "-0.03em"),
    "text1": (14, 18, 20, 28, "-0.03em"),
    "text2": (14, 18, 22, 26, "0"),
    "tab":  (20, 24, 28, 32, "normal"),
}

ROOT = 16  # px: what 1rem is on the page that reads the file (the static pages' old stylesheet sets html to 18px)

def rem(px): return f"{px / ROOT:.4f}".rstrip("0").rstrip(".") + "rem"

def fluid(lo, hi, max_vw=MAX_VW):
    if lo == hi: return rem(lo)
    assert hi / lo <= 2.5 + 1e-9, f"{lo}->{hi} grows more than 2.5x"
    assert lo >= 14, "under 14px"
    slope = (hi - lo) / (max_vw - MIN_VW)            # px per px of viewport
    intercept = lo - slope * MIN_VW                   # px
    sign = "+" if slope >= 0 else "-"
    return f"clamp({rem(lo)}, {rem(intercept)} {sign} {abs(slope) * 100:.4f}vw, {rem(hi)})"

def build(path, root, note):
    global ROOT
    ROOT = root
    out = [f"""/* GENERATED by scripts/build-type-scale.py — change the table there, not this file.

       The fluid type scale: --step-<name> is the font size, --step-<name>-lh its line height, --step-<name>-ls its letter
       spacing. Sizes run from the phone value at {MIN_VW}px wide to the desktop value at {MAX_VW}px and stay there; all in rem
       (WCAG 1.4.4: text follows the reader's setting and zooms to 200%). The same file feeds the React tokens
       (src/styles/globals.css) and the static pages (css/pages/*.css). {note} */

    :root {{"""]
    for name, (a, b, la, lb, ls, *vw) in STEPS.items():
        mv = vw[0] if vw else MAX_VW
        out.append(f"    --step-{name}: {fluid(a, b, mv)};")
        out.append(f"    --step-{name}-lh: {fluid(la, lb, mv)};")
        out.append(f"    --step-{name}-ls: {ls};")
    out.append("}\n")
    open(path, "w").write("\n".join(out))
    print("ok", path, len(STEPS), "steps")


build("public/css/type-scale.css", 16, "1rem = 16px here (the React app).")
build("public/css/type-scale-static.css", 18, "1rem = 18px here: the static pages' main stylesheet sets html to 18px.")
